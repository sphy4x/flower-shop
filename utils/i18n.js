function getInitialLang() {
  try {
    const saved = localStorage.getItem('ap_lang_v1');
    if (saved === 'ru' || saved === 'en' || saved === 'el') return saved;
    return 'ru';
  } catch (error) {
    console.error('getInitialLang error:', error);
    return 'ru';
  }
}

function saveLang(lang) {
  try {
    localStorage.setItem('ap_lang_v1', lang);
  } catch (error) {
    console.error('saveLang error:', error);
  }
}

function onLangChangeSubscribe(handler) {
  try {
    const h = () => {
      try {
        if (handler) handler(getInitialLang());
      } catch (error) {
        console.error('onLangChangeSubscribe handler error:', error);
      }
    };
    window.addEventListener('storage', h);
    return () => window.removeEventListener('storage', h);
  } catch (error) {
    console.error('onLangChangeSubscribe error:', error);
    return () => {};
  }
}

function getLocaleForLang(lang) {
  try {
    if (lang === 'en') return 'en-US';
    if (lang === 'el') return 'el-GR';
    return 'ru-RU';
  } catch (error) {
    console.error('getLocaleForLang error:', error);
    return 'ru-RU';
  }
}

